function normalizePersonName(first: string, last: string): string {
  return `${first} ${last}`.trim().replace(/\s+/g, " ").toLowerCase();
}

function extractPrimaryFirstName(firstName: string): string {
  let raw = String(firstName ?? "").trim();
  if (!raw) return "";
  raw = raw.replace(/^["']|["']$/g, "");
  raw = raw.replace(/\([^)]*\)/g, " ").trim();
  if (raw.includes('"')) {
    const quoted = raw.match(/"([^"]+)"/);
    if (quoted?.[1]) raw = quoted[1];
  }
  const token = raw.split(/\s+/)[0]?.replace(/[^a-zA-Z'-]/g, "") ?? "";
  return token.toLowerCase();
}

function textHintsGender(text: string): AthleteGender | null {
  const lower = text.toLowerCase();
  if (/\b(she\/her|her pronouns|women'?s|wsl women|female athlete|girl skater|b-girl)\b/.test(lower)) {
    return "female";
  }
  if (/\b(he\/him|his pronouns|men'?s tour|male athlete)\b/.test(lower)) {
    return "male";
  }
  if (/\b(they\/them|non-?binary|nonbinary)\b/.test(lower)) {
    return "non_binary";
  }
  return null;
}

export function inferAthleteGender(input: {
  first_name?: string | null;
  last_name?: string | null;
  sport?: string | null;
  about?: string | null;
  notes?: string | null;
  accolades?: string[] | null;
}): AthleteGender | null {
  if (isAthletePropertyEntry(input)) return null;

  const first = String(input.first_name ?? "").trim();
  const last = String(input.last_name ?? "").trim();
  const fullKey = normalizePersonName(first, last);
  if (fullKey && MANUAL_GENDER_BY_NAME[fullKey]) {
    return MANUAL_GENDER_BY_NAME[fullKey];
  }

  const contextText = [
    input.about,
    input.notes,
    ...(input.accolades ?? []),
    input.sport,
  ]
    .filter(Boolean)
    .join(" ");
  const hint = textHintsGender(contextText);
  if (hint) return hint;

  const primary = extractPrimaryFirstName(first);
  if (!primary) return null;

  const female = FEMALE_FIRST_NAMES.has(primary);
  const male = MALE_FIRST_NAMES.has(primary);
  if (female && !male) return "female";
  if (male && !female) return "male";

  // Ambiguous unisex names — sport/context heuristics
  if (primary === "jordan" || primary === "cameron" || primary === "riley" || primary === "charlie") {
    const sport = String(input.sport ?? "").toLowerCase();
    if (sport.includes("softball")) return "female";
    if (sport.includes("supercross") || sport.includes("motocross") || sport.includes("bmx")) return "male";
  }

  return null;
}
