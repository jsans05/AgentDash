export type AthleteGender = "female" | "male" | "non_binary";

export const ATHLETE_GENDER_OPTIONS: { value: AthleteGender; label: string }[] = [
  { value: "female", label: "Female" },
  { value: "male", label: "Male" },
  { value: "non_binary", label: "Non-binary" },
];

export function formatAthleteGender(gender: AthleteGender | null | undefined): string | null {
  if (!gender) return null;
  return ATHLETE_GENDER_OPTIONS.find((o) => o.value === gender)?.label ?? gender;
}

export function normalizeAthleteGender(raw: unknown): AthleteGender | null {
  const v = String(raw ?? "").trim().toLowerCase();
  if (!v) return null;
  if (v === "female" || v === "f" || v === "woman" || v === "women") return "female";
  if (v === "male" || v === "m" || v === "man" || v === "men") return "male";
  if (v === "non_binary" || v === "non-binary" || v === "nonbinary" || v === "nb") return "non_binary";
  return null;
}

const PROPERTY_SPORTS = new Set(["action sports - properties"]);

/** Roster entries that are brands, events, or teams — not individual athletes. */
export function isAthletePropertyEntry(input: {
  sport?: string | null;
  last_name?: string | null;
  first_name?: string | null;
}): boolean {
  const sport = String(input.sport ?? "").trim().toLowerCase();
  if (PROPERTY_SPORTS.has(sport)) return true;
  const last = String(input.last_name ?? "").trim();
  const first = String(input.first_name ?? "").trim();
  if (!last && first.split(/\s+/).length >= 2) {
    const lower = first.toLowerCase();
    if (
      lower.includes("motorsports") ||
      lower.includes("media") ||
      lower.includes("racing") ||
      lower.includes("factory") ||
      lower.includes("international") ||
      lower.includes("wellness") ||
      lower.includes("selection") ||
      lower.includes("berrics") ||
      lower.includes("uninvited") ||
      lower.includes("hammers")
    ) {
      return true;
    }
  }
  return false;
}

